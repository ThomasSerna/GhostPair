export function translator(locale: Locale) {
  return (message: Message, values: Record<string, string | number> = {}): string =>
    (locale === 'es' ? spanish[message] : message).replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
